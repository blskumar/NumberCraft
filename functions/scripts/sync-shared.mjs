// Copies the pure shared modules from ../lib into src/shared so the functions
// package is self-contained at deploy time (only functions/ is uploaded).
// The copies are committed; lib/server-sync.test.ts fails if they drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const lib = path.resolve(here, '../../lib');
const out = path.resolve(here, '../src/shared');
fs.mkdirSync(out, { recursive: true });
for (const f of ['name-moderation.ts', 'name-blocklist.ts']) {
  const src = fs.readFileSync(path.join(lib, f), 'utf8');
  fs.writeFileSync(
    path.join(out, f),
    `// GENERATED by functions/scripts/sync-shared.mjs from lib/${f}. Do not edit.\n${src}`
  );
}
console.log('shared modules synced');
