// Generates app/dark-theme.generated.css: a dark counterpart for every arbitrary
// hex colour utility used in components/ and app/.
//   node scripts/gen-dark-theme.mjs          rewrite the file
//   node scripts/gen-dark-theme.mjs --check  exit 1 if the file is stale (CI guard)
import fs from 'node:fs';
import path from 'node:path';

const roots = ['components', 'app'];
const out = 'app/dark-theme.generated.css';
const re = /((?:[a-z][a-z-]*:)*)(bg|text|border|ring|fill|stroke|from|to|via|outline|divide|decoration|placeholder)-\[#([0-9a-fA-F]{6})\](?:\/(\d+))?/g;

function walk(d, acc = []) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p, acc);
    else if (/\.(tsx|ts)$/.test(f.name) && !/\.test\./.test(f.name)) acc.push(p);
  }
  return acc;
}

function hsl(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2;
  const d = mx - mn;
  let h = 0, s = 0;
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1));
    h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h = (h * 60 + 360) % 360;
  }
  return { h, s, l };
}
const css = ({ h, s, l }) => `hsl(${Math.round(h)} ${Math.round(s * 100)}% ${Math.round(l * 1000) / 10}%)`;

// kind: surface (bg/from/to/via/fill), ink (text/fill-as-ink), line (border/ring/divide/stroke)
function dark(kind, hex) {
  const c = hsl(hex);
  if (kind === 'surface') {
    if (c.l < 0.6) return null; // already a saturated/dark fill (buttons, bars)
    return css({ h: c.h, s: Math.min(c.s, 0.4) * 0.5, l: c.s > 0.25 ? 0.17 : 0.16 + (1 - c.l) * 0.6 });
  }
  if (kind === 'line') {
    if (c.l < 0.55) return null;
    return css({ h: c.h, s: Math.min(c.s, 0.4) * 0.5, l: c.s > 0.25 ? 0.32 : 0.24 });
  }
  // ink: lighten anything too dark for a dark page
  if (c.l >= 0.62) return null;
  return css({ h: c.h, s: Math.min(1, c.s * 1.05), l: Math.max(0.74, 1 - c.l * 0.55) });
}

const kindOf = (u) =>
  ['bg', 'from', 'to', 'via'].includes(u) ? 'surface' : ['border', 'ring', 'divide', 'outline'].includes(u) ? 'line' : 'ink';
const propOf = {
  bg: 'background-color', from: '--tw-gradient-from', to: '--tw-gradient-to', via: '--tw-gradient-via',
  text: 'color', placeholder: 'color', decoration: 'text-decoration-color',
  border: 'border-color', ring: '--tw-ring-color', divide: 'border-color', outline: 'outline-color',
  fill: 'fill', stroke: 'stroke',
};
const esc = (s) => s.replace(/([^a-zA-Z0-9_-])/g, '\\$1');

const rules = new Map();
for (const root of roots) for (const f of walk(root)) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(re)) {
    const [full, variants, util, hex, op] = m;
    let kind = kindOf(util);
    if (util === 'fill' || util === 'stroke') {
      // pale fills/strokes are surfaces/lines, dark ones are ink
      const l = hsl(hex).l;
      kind = l >= 0.8 ? (util === 'fill' ? 'surface' : 'line') : 'ink';
    }
    const val = dark(kind, hex);
    if (!val) continue;
    const vs = variants ? variants.split(':').filter(Boolean) : [];
    if (vs.some((v) => !['hover', 'focus', 'active', 'disabled', 'focus-visible', 'group-hover', 'sm', 'md', 'lg'].includes(v))) continue;
    const pseudo = vs.filter((v) => ['hover', 'focus', 'active', 'disabled', 'focus-visible'].includes(v)).map((v) => ':' + v).join('');
    const group = vs.includes('group-hover');
    const sel = `.${esc(full)}`;
    const color = op ? `color-mix(in srgb, ${val} ${op}%, transparent)` : val;
    const target = group ? `.group:hover ${sel}` : `${sel}${pseudo}`;
    const decl = propOf[util] === '--tw-ring-color' ? `${propOf[util]}: ${color}` : `${propOf[util]}: ${color}`;
    rules.set(full, `html[data-theme="dark"] ${target} { ${decl} !important; }`);
  }
}

const body =
  '/* GENERATED by scripts/gen-dark-theme.mjs - do not edit. Dark counterparts for every hex colour utility. */\n' +
  [...rules.values()].sort().join('\n') + '\n';

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('dark-theme.generated.css is stale: run node scripts/gen-dark-theme.mjs'); process.exit(1); }
  console.log('dark theme map up to date (' + rules.size + ' rules)');
} else {
  fs.writeFileSync(out, body);
  console.log('wrote', out, rules.size, 'rules');
}
